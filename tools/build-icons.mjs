// Regenerates assets/js/icons.js from the official Lucide SVGs (+ brand logos from Bootstrap Icons).
//
// Usage (from the project root):
//   npm install --no-save lucide-static bootstrap-icons
//   node tools/build-icons.mjs
//
// To add an icon: find its name on https://lucide.dev/icons, add it to LUCIDE below, re-run.
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const NM = process.env.ICON_NODE_MODULES || path.join(root, "node_modules");
for (const pkg of ["lucide-static", "bootstrap-icons"]) {
  if (!fs.existsSync(path.join(NM, pkg))) {
    console.error(`Missing ${pkg}. Run: npm install --no-save lucide-static bootstrap-icons`);
    process.exit(1);
  }
}
const lucideVersion = JSON.parse(fs.readFileSync(`${NM}/lucide-static/package.json`, "utf8")).version;

const LUCIDE = [
  // general UI
  "arrow-right", "arrow-up-right", "check", "chevron-down", "chevron-left", "chevron-right",
  "circle-alert", "copy", "info", "search", "x", "zoom-in", "image", "link", "tag", "menu",
  // contact / meta
  "mail", "phone", "map-pin", "calendar", "calendar-clock", "clock", "hourglass", "user", "users",
  "building-2", "coins", "wallet", "id-card", "badge-check", "clipboard-check", "file-text",
  "graduation-cap", "briefcase",
  // research / lab
  "layers", "flask-conical", "microscope", "zap", "grid-3x3", "factory", "cpu", "monitor",
  "chart-line", "flame", "thermometer", "refresh-cw", "radio", "server", "activity", "shield-check",
  "atom", "target", "handshake", "settings", "rocket", "lightbulb", "palette", "code", "sparkles",
  "award", "book-open",
];

// Brand logos (Lucide has none). Bootstrap Icons (MIT) + Simple Icons-style paths already used on the site.
const bi = name => {
  const svg = fs.readFileSync(`${NM}/bootstrap-icons/icons/${name}.svg`, "utf8");
  return { viewBox: "0 0 16 16", body: svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim() };
};
const BRANDS = {
  linkedin: bi("linkedin"),
  github: bi("github"),
  x: bi("twitter-x"),
  "google-scholar": {
    viewBox: "0 0 24 24",
    body: '<path d="M12 24a7 7 0 1 1 0-14 7 7 0 0 1 0 14zm0-24L0 9.5l4.838 3.94A8 8 0 0 1 12 9a8 8 0 0 1 7.162 4.44L24 9.5z"/>',
  },
};

const lucideBody = name => {
  const svg = fs.readFileSync(`${NM}/lucide-static/icons/${name}.svg`, "utf8");
  return svg
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .split("\n").map(l => l.trim()).filter(Boolean).join("")
    .replace(/\s*\/>/g, "/>");
};

const lines = LUCIDE.map(n => `  "${n}": '${lucideBody(n)}',`);
const brandLines = Object.entries(BRANDS).map(([n, b]) =>
  `  "${n}": { viewBox: "${b.viewBox}", body: '${b.body.replace(/\s*\n\s*/g, "").replace(/'/g, "\\'")}' },`);

const out = `// Site icon set — generated from lucide-static v${lucideVersion} (ISC licence, https://lucide.dev)
// plus brand logos (Bootstrap Icons, MIT). Generated by tools/build-icons.mjs — to add an icon,
// add its Lucide name (https://lucide.dev/icons) to the list in that script and re-run it.
//
// Usage in JS:   icon("mail")  ·  icon("mail", { size: 18, className: "my-icon", label: "Email" })
// Usage in HTML: <i data-icon="mail"></i>   (replaced automatically by app.js, incl. content added later)

const LUCIDE = {
${lines.join("\n")}
};

const BRANDS = {
${brandLines.join("\n")}
};

const escAttr = v => String(v).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");

export const hasIcon = name => Object.hasOwn(LUCIDE, name) || Object.hasOwn(BRANDS, name);

/**
 * Returns an inline SVG string. Unknown names return "" (so bad data never breaks a layout).
 * Icons inherit the text colour (currentColor) and default to 1em, so they scale with font-size.
 */
export function icon(name, { size, className = "", label, strokeWidth } = {}) {
  const key = String(name || "").trim();
  const brand = BRANDS[key];
  const body = brand ? brand.body : LUCIDE[key];
  if (!body) return "";

  const dims = size ? \` width="\${size}" height="\${size}"\` : "";
  const a11y = label ? \` role="img" aria-label="\${escAttr(label)}"\` : \` aria-hidden="true" focusable="false"\`;
  const cls = \`icon icon-\${key}\${className ? " " + className : ""}\`;

  return brand
    ? \`<svg class="\${cls}" viewBox="\${brand.viewBox}" fill="currentColor"\${dims}\${a11y}>\${body}</svg>\`
    : \`<svg class="\${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="\${strokeWidth || 2}" stroke-linecap="round" stroke-linejoin="round"\${dims}\${a11y}>\${body}</svg>\`;
}

/** Replaces every <i data-icon="name"> inside root with its SVG (keeps the element's classes). */
export function hydrateIcons(root = document) {
  root.querySelectorAll("i[data-icon]").forEach(el => {
    const svg = icon(el.dataset.icon, {
      className: el.className,
      label: el.getAttribute("aria-label") || undefined,
      size: el.dataset.size,
      strokeWidth: el.dataset.stroke,
    });
    if (svg) el.outerHTML = svg;
  });
}
`;

fs.writeFileSync(path.join(root, "assets/js/icons.js"), out.replace(/\r?\n/g, "\n"));
console.log(`icons.js: ${LUCIDE.length} lucide + ${Object.keys(BRANDS).length} brand icons, lucide v${lucideVersion}`);
